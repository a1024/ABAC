enum
{
	FILTREACH=8,
	FILTWIDTH=2*FILTREACH+1,
	FILTSTRIDE=2*FILTWIDTH,
	KERNSIZE=2*FILTREACH*(FILTREACH+1),
	FILTSIZE=KERNSIZE*2,//pixel, delta
	FILTBUFSIZE=FILTSIZE+2,//...scalarflag, scalar/shift_right
};
static int filt_reduce(int16_t *filt)
{
	int c=0;
	
	for(int k=0;k<FILTSIZE;++k)
		c|=filt[k];
	c=_tzcnt_u32(c);
	if(c)
	{
		for(int k=0;k<FILTSIZE;++k)
			filt[k]>>=c;
		filt[FILTSIZE+1]-=c;
	}

	c=0;
	for(int k=0;k<FILTSIZE;++k)
	{
		int val=abs(filt[k]);
		if(c<val)
			c=val;
	}
	c=32-_lzcnt_u32(c);
	if(c>10)
	{
		int d=c-10;
		for(int k=0;k<FILTSIZE;++k)
			filt[k]>>=d;
		filt[FILTSIZE+1]+=d;
		c-=10;
	}
	return c;
}
static void filt_add(int16_t *dst, int16_t *src)
{
	//filt_reduce(src);
	//filt_reduce(dst);
	int sh=src[FILTSIZE+1]-dst[FILTSIZE+1];

	if(sh<0)
	{
		sh=-sh;
		for(int k=0;k<FILTSIZE;++k)
			dst[k]=dst[k]+(src[k]<<sh);
	}
	else if(sh>0)
	{
		for(int k=0;k<FILTSIZE;++k)
			dst[k]=(dst[k]<<sh)+src[k];
		dst[FILTSIZE+1]+=sh;
	}
	else
	{
		for(int k=0;k<FILTSIZE;++k)
			dst[k]+=src[k];
	}
	filt_reduce(dst);
}

static int parse_shift(const char **expr, int16_t *filt);
static void skip_space(const char **str)
{
	while(**str==' ')
		++*str;
}
static int parse_unary(const char **expr, int16_t *filt)
{
	for(;;)
	{
		skip_space(expr);
		switch(**expr)
		{
		case '(':
			++*expr;//skip '('
			skip_space(expr);
			parse_shift(expr, filt);
			skip_space(expr);
			++*expr;//skip ')'
			skip_space(expr);
			return 0;
		case '+':
			++*expr;//skip '+'
			continue;
		case '-':
			++*expr;//skip '-'
			skip_space(expr);
			parse_unary(expr, filt);
			skip_space(expr);
			if(filt[FILTSIZE])
				filt[FILTSIZE+1]=-filt[FILTSIZE+1];
			else
			{
				for(int k=0;k<FILTSIZE;++k)
					filt[k]=-filt[k];
			}
			return 0;
		case '0':case '1':case '2':case '3':case '4':case '5':case '6':case '7':case '8':case '9':
			{
				filt[FILTSIZE+0]=1;
				filt[FILTSIZE+1]=(int16_t)strtol(*expr, expr, 10);
				skip_space(expr);
			}
			return 0;
		case 'd':
		case 'N':
		case 'W':
			{
				int py=FILTREACH, px=FILTREACH, delta=**expr=='d';

				*expr+=delta;
				while(**expr=='N')
				{
					--py;
					++*expr;
				}
				while(**expr=='W')
				{
					--px;
					++*expr;
				}
				while(**expr=='E')
				{
					++px;
					++*expr;
				}
				skip_space(expr);
				if(py<0||py>FILTREACH||px-FILTREACH<-FILTREACH||px-FILTREACH>FILTREACH||FILTWIDTH*py+px>=KERNSIZE)
					CRASH("");
				filt[FILTSIZE]=0;
				++filt[2*(FILTWIDTH*py+px)+delta];
			}
			return 0;
		}
		break;
	}
	return 0;
}
static int parse_mul(const char **expr, int16_t *filt)
{
	parse_unary(expr, filt);
	for(;;)
	{
		skip_space(expr);
		switch(**expr)
		{
		case '*':
			{
				int16_t f2[FILTBUFSIZE]={0};

				++*expr;//skip op
				skip_space(expr);
				parse_unary(expr, f2);
				skip_space(expr);
				if(filt[FILTSIZE]&&!f2[FILTSIZE])
				{
					for(int k=0;k<FILTSIZE;++k)
						f2[k]*=filt[FILTSIZE+1];
					memcpy(filt, f2, sizeof(int16_t[FILTSIZE+2]));
				}
				else if(!filt[FILTSIZE]&&f2[FILTSIZE])
				{
					for(int k=0;k<FILTSIZE;++k)
						filt[k]*=f2[FILTSIZE+1];
				}
				else if(filt[FILTSIZE]&&f2[FILTSIZE])
					filt[FILTSIZE+1]*=f2[FILTSIZE+1];
				else//can't mul pixels
					CRASH("");
				if(!filt[FILTSIZE])
					filt_reduce(filt);
			}
			continue;
		}
		break;
	}
	return 0;
}
static int parse_add(const char **expr, int16_t *filt)
{
	parse_mul(expr, filt);
	for(;;)
	{
		skip_space(expr);
		switch(**expr)
		{
		case '+':
		case '-':
			{
				int16_t f2[FILTBUFSIZE]={0};
				int sub=**expr=='-';

				++*expr;//skip op
				skip_space(expr);
				parse_mul(expr, f2);
				skip_space(expr);
				if(filt[FILTSIZE]&&f2[FILTSIZE])
				{
					if(sub)
						f2[FILTSIZE+1]=-f2[FILTSIZE+1];
					filt[FILTSIZE+1]+=f2[FILTSIZE+1];
				}
				else if(!filt[FILTSIZE]&&!f2[FILTSIZE])
				{
					if(sub)
					{
						for(int k=0;k<FILTSIZE;++k)
							f2[k]=-f2[k];
					}
					filt_add(filt, f2);
				}
				else//can't add pixel and number
					CRASH("");
			}
			continue;
		}
		break;
	}
	return 0;
}
static int parse_shift(const char **expr, int16_t *filt)
{
	parse_add(expr, filt);
	skip_space(expr);
	while(**expr=='<'||**expr=='>')
	{
		int right=**expr=='>', c=0;

		if(filt[FILTSIZE])//must be filt
			CRASH("");
		*expr+=2;//skip ">>"
		skip_space(expr);
		c=strtol(*expr, expr, 10);
		if(!right)
			c=-c;
		filt[FILTSIZE+1]+=c;
		filt_reduce(filt);
	}
	return 0;
}

